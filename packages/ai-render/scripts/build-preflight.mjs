// Writes src/preflight.ts from tailwindcss/preflight.css (MIT): the reset AI blocks are written against. The iframe
// runtime and the HTML export load it before the compiled utilities. `--check` fails when the file is stale.
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const pkg = require("tailwindcss/package.json");
const css = await readFile(require.resolve("tailwindcss/preflight.css"), "utf8");
// The theme of AI blocks has no `--default-font-family`: the body font of the doc is the default.
const body = css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\n{2,}/g, "\n").trim();
const out = `// Generated by scripts/build-preflight.mjs from tailwindcss@${pkg.version}/preflight.css (MIT License,
// Copyright (c) Tailwind Labs, Inc.). Do not edit.
export const PREFLIGHT_CSS = ${JSON.stringify(body + "\n")};
`;
const target = new URL("../src/preflight.ts", import.meta.url);
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== out) {
    console.error("src/preflight.ts is stale: run pnpm preflight");
    process.exit(1);
  }
} else {
  await writeFile(target, out);
}
