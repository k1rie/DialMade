// Copies the default theme of tailwindcss (MIT, see NOTICE) into src/defaults/tailwind.generated.ts,
// so imports can tell «framework default» values from the user's brand. `--check` fails when stale.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const out = join(root, "src/defaults/tailwind.generated.ts");

const pkgPath = require.resolve("tailwindcss/package.json");
const { version } = JSON.parse(readFileSync(pkgPath, "utf8"));
const css = readFileSync(join(dirname(pkgPath), "theme.css"), "utf8");

/** Top-level declarations of every `@theme default …{}` block (nested at-rules such as @keyframes are skipped). */
function themeDeclarations(text) {
  const vars = new Map();
  const blockStart = /@theme default[^{]*\{/g;
  let match;
  while ((match = blockStart.exec(text))) {
    let depth = 1;
    let decl = "";
    for (let i = match.index + match[0].length; i < text.length && depth > 0; i++) {
      const ch = text[i];
      if (ch === "{") depth++;
      else if (ch === "}") {
        depth--;
        if (depth === 1) decl = "";
      } else if (depth === 1) {
        if (ch === ";") {
          const colon = decl.indexOf(":");
          if (colon > 0) {
            const name = decl.slice(0, colon).trim();
            const value = decl.slice(colon + 1).replace(/\s+/g, " ").trim();
            if (name.startsWith("--") && !vars.has(name)) vars.set(name, value);
          }
          decl = "";
        } else {
          decl += ch;
        }
      }
    }
  }
  return vars;
}

const vars = themeDeclarations(css);
const lines = [...vars].map(([name, value]) => `  ${JSON.stringify(name)}: ${JSON.stringify(value)},`);
const source = `// Generated by scripts/build-tailwind-defaults.mjs from tailwindcss@${version}/theme.css.
// Tailwind CSS is MIT licensed (Copyright (c) Tailwind Labs, Inc.); see NOTICE. Do not edit by hand.

export const TAILWIND_VERSION = ${JSON.stringify(version)};

/** Every variable of Tailwind's default theme, as written in theme.css (multi-line values joined). */
export const TAILWIND_THEME_VARS: Readonly<Record<string, string>> = {
${lines.join("\n")}
};
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(out, "utf8");
  if (current !== source) {
    console.error(`${out} is stale: run pnpm --filter @dialmade/import defaults`);
    process.exit(1);
  }
  console.log(`tailwind defaults up to date (${vars.size} vars, tailwindcss@${version})`);
} else {
  writeFileSync(out, source);
  console.log(`wrote ${vars.size} vars from tailwindcss@${version}`);
}
