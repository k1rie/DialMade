const variantName = (names: Record<string, string>, id: string) =>
  Object.hasOwn(names, id) ? (names[id] ?? id) : capitalize(id.replace(/[-_]/g, " "));

function estimateEs(estimate: ContentEstimate): string {
  if (estimate.kind === "count") return plural(estimate.value, ...UNITS_ES[estimate.unit]);
  if (estimate.kind === "variant") return variantName(VARIANTS_ES, estimate.value);
  return estimate.value;
}

function estimateEn(estimate: ContentEstimate): string {
  if (estimate.kind === "count") return plural(estimate.value, ...UNITS_EN[estimate.unit]);
  if (estimate.kind === "variant") return variantName(VARIANTS_EN, estimate.value);
  return estimate.value;
}

